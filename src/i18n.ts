// UI texts. The German dictionary is the source; every other one is typed as
// `Record<MessageKey, string>`, so missing or extra keys are type errors.
// Placeholders: `{name}`, identical in all languages (checked by i18n.test.ts).
//
// Form of address: informal "you" per project rule wherever software in that language uses it
// (en, es, fr, el, it, pl, pt, ru, tr), otherwise a neutral imperative. Greek uses the second person
// singular ("Επίλεξε", "σου"), Russian uses "ты" ("Выбери", "твой"). Japanese and Chinese stay
// neutrally polite and avoid direct address where possible.
//
// Portuguese means Brazilian Portuguese (pt-BR): it has by far the most speakers, most developer
// tools (VS Code, GitHub) only offer pt-BR, and readers from Portugal understand it well.
// Wording is kept as neutral as possible.
//
// Texts with {count} are only used for two or more (update.endsMany). Where a language needs one
// form for 2 to 4 and another from 5 up (pl, ru), the sentence works with any number ("…: {count}.").

